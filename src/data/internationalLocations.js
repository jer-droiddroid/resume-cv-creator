/**
 * Formats country and city cleanly into a resume location string.
 */
export function formatLocation(country, city) {
  const cleanCountry = (country || '').trim()
  const cleanCity = (city || '').trim()

  if (!cleanCountry && !cleanCity) return ''
  if (!cleanCountry) return cleanCity
  if (!cleanCity) return cleanCountry

  if (cleanCountry.toLowerCase() === cleanCity.toLowerCase()) {
    return cleanCountry
  }

  if (cleanCity.toLowerCase().endsWith(cleanCountry.toLowerCase())) {
    return cleanCity
  }

  return `${cleanCity}, ${cleanCountry}`
}

/**
 * Reverse-parses an existing location string (e.g. "Manila, Philippines" or "San Francisco, CA")
 * into country, city, and custom-city state.
 */
export function parseLocation(rawLocation) {
  if (!rawLocation || typeof rawLocation !== 'string' || !rawLocation.trim()) {
    return { country: '', city: '', isCustomCity: false }
  }

  const trimmed = rawLocation.trim()

  // 1. Direct match with a country name (e.g. "Singapore" or "Philippines")
  const exactCountry = INTERNATIONAL_COUNTRIES.find(
    (c) => c.name.toLowerCase() === trimmed.toLowerCase()
  )
  if (exactCountry) {
    if (exactCountry.cities.length === 1 && exactCountry.cities[0].toLowerCase() === trimmed.toLowerCase()) {
      return { country: exactCountry.name, city: exactCountry.cities[0], isCustomCity: false }
    }
    return { country: exactCountry.name, city: '', isCustomCity: false }
  }

  // 2. Comma-separated: check if the suffix matches a known country name
  const lastCommaIdx = trimmed.lastIndexOf(',')
  if (lastCommaIdx > -1) {
    const cityPart = trimmed.slice(0, lastCommaIdx).trim()
    const countryPart = trimmed.slice(lastCommaIdx + 1).trim()

    const matchedCountry = INTERNATIONAL_COUNTRIES.find(
      (c) => c.name.toLowerCase() === countryPart.toLowerCase()
    )

    if (matchedCountry) {
      const knownCity = matchedCountry.cities.find(
        (ct) => ct.toLowerCase() === cityPart.toLowerCase()
      )
      return {
        country: matchedCountry.name,
        city: knownCity || cityPart,
        isCustomCity: !knownCity,
      }
    }
  }

  // 3. Known US city/state format without "United States" (e.g. "San Francisco, CA" or "New York, NY")
  const usCountry = INTERNATIONAL_COUNTRIES.find((c) => c.code === 'US')
  if (usCountry) {
    const knownUsCity = usCountry.cities.find(
      (ct) => ct.toLowerCase() === trimmed.toLowerCase()
    )
    if (knownUsCity) {
      return { country: 'United States', city: knownUsCity, isCustomCity: false }
    }
  }

  // 4. Check if trimmed string matches any known city across all countries
  for (const country of INTERNATIONAL_COUNTRIES) {
    const matchedCity = country.cities.find(
      (ct) => ct.toLowerCase() === trimmed.toLowerCase()
    )
    if (matchedCity) {
      return { country: country.name, city: matchedCity, isCustomCity: false }
    }
  }

  // 5. Fallback: unparsed / custom location with no country
  return { country: '', city: trimmed, isCustomCity: true }
}
